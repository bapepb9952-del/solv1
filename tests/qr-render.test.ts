import { expect, it } from "vitest";
import QRCode from "qrcode";
import jsQR from "jsqr";
import { QR_PREFIX, qrTokenSchema } from "../src/features/check-ins/qr-schema";

it("decodes the actual versioned payload generated by qrcode with the scanner's jsQR library", () => {
  const payload = QR_PREFIX + "a".repeat(64);
  const { modules } = QRCode.create(payload, { errorCorrectionLevel: "M" });
  const scale = 6, margin = 4, size = (modules.size + 2 * margin) * scale;
  const pixels = new Uint8ClampedArray(size * size * 4).fill(255);
  for (let y = 0; y < modules.size; y++) for (let x = 0; x < modules.size; x++) {
    if (!modules.get(y, x)) continue;
    for (let dy = 0; dy < scale; dy++) for (let dx = 0; dx < scale; dx++) {
      const index = ((y * scale + margin * scale + dy) * size + x * scale + margin * scale + dx) * 4;
      pixels[index] = pixels[index + 1] = pixels[index + 2] = 0;
    }
  }
  const decoded = jsQR(pixels, size, size, { inversionAttempts: "dontInvert" });
  expect(decoded?.data).toBe(payload);
  expect(qrTokenSchema.parse(decoded!.data)).toBe("a".repeat(64));
});
